import re
_INTERNO = [re.compile(r'\s*\(prueba de [a-z]+\)'), re.compile(r'\s*\((?:valida )?[A-Z]+_[A-Z0-9_]*(?: = [\d.,]+)?\)'), re.compile(r'\s*\([A-Z_]{3,} = [\d.,]+\)')]

SUBS = [(' - DECISIÓN (vacío = sugerido)', ' - decisión'), (' - sugerido', ' - plan'), ('TRMA (PRIMA_ADIC ajustada)', 'TRMA')]

def aplicar(wb):
    n = 0
    for ws in wb.worksheets:
        for row in ws.iter_rows():
            for c in row:
                v = c.value
                if not isinstance(v, str) or v.startswith('='): continue
                nv = v
                for pre, new in TEXTOS:
                    if v.startswith(pre):
                        nv = new; break
                if isinstance(nv, str):
                    for a, b in SUBS: nv = nv.replace(a, b)
                    for p in _INTERNO: nv = p.sub('', nv)
                if nv != v:
                    c.value = nv; n += 1
        if ws.title in ('Supuestos',):
            pass
    return n
